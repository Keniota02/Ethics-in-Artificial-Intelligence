"""RQ1: measure how machine-learning selectors reproduce or amplify the RAE.

Historical cohorts are generated by a human-like scout. ML models are trained
on those cohorts and evaluated on a fresh test cohort, alongside the historical
selector and an Oracle benchmark.

The experiment varies:
- historical selector: scout or biased scout;
- feedback exposure: off (0) or on (1);
- label regime: historical decisions or next-stage performance;
- birth information: withheld or included;
- ML model: pooled linear, linear by stage, or gradient boosting.

Usage:
    python -m experiments.run_rq1 [--seeds 20] [--model linear]
                                  [--athletes 20000]

Results are saved under ``results/`` and are not tracked by Git.
"""

from argparse import ArgumentParser
from dataclasses import replace
from itertools import product
from numbers import Integral

import pandas as pd
from experiments.common import (
    EXPOSURES,
    HISTORICAL,
    N_HISTORICAL_COHORTS,
    REGIMES,
    fmt,
    save,
)

from rae.config import SimConfig
from rae.learning import train_selector
from rae.metrics import summarize_talent_metrics
from rae.pipeline import simulate
from rae.selectors import OracleSelector

MODEL_KINDS = ("linear", "linear_by_stage", "gbm")

BASELINE = "historical selector"

METRICS = (
    "selection_rate_ratio_q1_q4",
    "overall_talent_loss",
    "talent_loss_q4",
    "equal_opportunity_gap",
    "mean_selected_talent",
    "regret",
)


def selector_name(regime: str, use_birth_info: bool) -> str:
    """Return a readable label for an ML selector configuration."""
    birth_label = "yes" if use_birth_info else "no"
    return f"ML {regime}, birth info {birth_label}"


def _validate_positive_integer(name: str, value: int) -> int:
    """Validate a positive integer experiment parameter."""
    if isinstance(value, bool) or not isinstance(value, Integral):
        raise TypeError(f"{name} must be an integer.")

    value = int(value)

    if value < 1:
        raise ValueError(f"{name} must be greater than or equal to 1.")

    return value


def _final_stage_metrics(
    simulation: pd.DataFrame,
    config: SimConfig,
) -> dict[str, float]:
    """Extract the configured fairness and efficiency metrics at the final stage."""
    summary = summarize_talent_metrics(
        simulation,
        top_talent_fraction=config.top_talent_fraction,
        adult_maturation_weight=config.adult_maturation_weight,
    )

    final_stage = summary.loc[summary["stage"] == config.n_stages - 1]

    if len(final_stage) != 1:
        raise ValueError("simulation metrics do not contain exactly one final-stage row.")

    return {metric: float(final_stage.iloc[0][metric]) for metric in METRICS}


def run(
    n_seeds: int = 20,
    model_kind: str = "linear",
    n_athletes: int = 20_000,
) -> pd.DataFrame:
    """Run RQ1 over historical selectors, exposure settings and random seeds.

    For each combination, three independent historical cohorts are generated.
    The fitted models and the historical selector are then evaluated on the
    same fresh test cohort, using common random numbers.

    Returns
    -------
    pd.DataFrame
        One row per seed, exposure setting, historical selector and evaluated
        selector. Metrics refer to the final selection stage.
    """
    n_seeds = _validate_positive_integer("n_seeds", n_seeds)
    n_athletes = _validate_positive_integer("n_athletes", n_athletes)

    if model_kind not in MODEL_KINDS:
        raise ValueError(f"model_kind must be one of {MODEL_KINDS}.")

    rows = []

    for exposure, (historical_name, historical_selector) in product(
        EXPOSURES,
        HISTORICAL.items(),
    ):
        base_config = SimConfig(
            n_athletes=n_athletes,
            exposure_weight=exposure,
        )

        for seed in range(n_seeds):
            # Generate independent historical cohorts using deterministic seeds.
            historical_cohorts = [
                simulate(
                    replace(base_config, seed=seed * 1_000 + cohort_index),
                    historical_selector,
                )
                for cohort_index in range(N_HISTORICAL_COHORTS)
            ]

            # Every evaluated selector faces the same fresh test cohort and
            # the same pre-generated simulation random streams.
            test_config = replace(
                base_config,
                seed=seed * 1_000 + 999,
            )

            selectors = {
                "oracle": OracleSelector(),
                BASELINE: historical_selector,
            }

            for regime, use_birth_info in product(REGIMES, (False, True)):
                name = selector_name(regime, use_birth_info)

                selectors[name] = train_selector(
                    historical_cohorts,
                    regime=regime,
                    use_birth_info=use_birth_info,
                    model_kind=model_kind,
                    seed=seed,
                )

            for name, selector in selectors.items():
                simulation = simulate(test_config, selector)
                metrics = _final_stage_metrics(simulation, test_config)

                rows.append(
                    {
                        "exposure_weight": exposure,
                        "historical_selector": historical_name,
                        "seed": seed,
                        "model_kind": model_kind,
                        "selector": name,
                        "evaluation_stage": test_config.n_stages - 1,
                        **metrics,
                    }
                )

    return pd.DataFrame(rows)


def report(runs: pd.DataFrame) -> None:
    """Print mean confidence intervals and paired Q1/Q4 changes by experiment."""
    required_columns = {
        "exposure_weight",
        "historical_selector",
        "seed",
        "selector",
        *METRICS,
    }

    missing = required_columns - set(runs.columns)

    if missing:
        raise ValueError(f"experiment results are missing columns: {sorted(missing)}.")

    if runs.empty:
        raise ValueError("experiment results must not be empty.")

    selector_order = list(runs["selector"].drop_duplicates())

    for (exposure, historical_name), block in runs.groupby(
        ["exposure_weight", "historical_selector"],
        sort=False,
    ):
        loop_label = "on" if exposure > 0.0 else "off"

        print(
            f"\n=== historical: {historical_name}, "
            f"exposure_weight = {exposure:g} (loop {loop_label}) ==="
        )

        print(
            f"{'selector':39s}"
            + "".join(f"{metric[:19]:>22s}" for metric in METRICS)
            + f"{'paired Δ Q1/Q4':>23s}"
        )

        ratio_by_seed = block.pivot(
            index="seed",
            columns="selector",
            values="selection_rate_ratio_q1_q4",
        )

        for name in selector_order:
            selector_rows = block.loc[block["selector"] == name]

            if selector_rows.empty:
                continue

            metric_values = [fmt(selector_rows[metric]) for metric in METRICS]

            if name == BASELINE:
                paired_delta = "—"
            elif BASELINE in ratio_by_seed.columns and name in ratio_by_seed.columns:
                paired_difference = ratio_by_seed[name] - ratio_by_seed[BASELINE]
                paired_delta = fmt(paired_difference)
            else:
                paired_delta = "n/a"

            print(
                f"{name:39s}"
                + "".join(f"{value:>22s}" for value in metric_values)
                + f"{paired_delta:>23s}"
            )


def main() -> None:
    """Parse command-line arguments, run RQ1 and save the raw results."""
    parser = ArgumentParser(description=__doc__.split("\n")[0])

    parser.add_argument(
        "--seeds",
        type=int,
        default=20,
        help="number of independent random seeds (default: 20)",
    )
    parser.add_argument(
        "--model",
        choices=MODEL_KINDS,
        default="linear",
        help="ML model architecture (default: linear)",
    )
    parser.add_argument(
        "--athletes",
        type=int,
        default=20_000,
        help="initial athletes per cohort (default: 20000)",
    )

    args = parser.parse_args()

    results = run(
        n_seeds=args.seeds,
        model_kind=args.model,
        n_athletes=args.athletes,
    )

    output_path = save(
        results,
        f"rq1_runs_{args.model}.csv",
    )

    print(f"Results saved to: {output_path}")
    report(results)


if __name__ == "__main__":
    main()
